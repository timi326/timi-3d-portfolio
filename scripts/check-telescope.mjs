import assert from 'node:assert/strict';
import {readFile,writeFile,mkdir} from 'node:fs/promises';
import ts from 'typescript';
import * as THREE from 'three';
import {GLTFLoader} from 'three/examples/jsm/loaders/GLTFLoader.js';
await mkdir('artifacts/orbit/check', {recursive:true});
for (const name of ['telescope','scene-layout']) await writeFile(`artifacts/orbit/check/${name}.mjs`,ts.transpileModule(await readFile(`app/${name}.ts`,'utf8'),{compilerOptions:{module:ts.ModuleKind.ESNext,target:ts.ScriptTarget.ES2022}}).outputText);
const {loadTelescope} = await import('../artifacts/orbit/check/telescope.mjs');
const {SceneLayout} = await import('../artifacts/orbit/check/scene-layout.mjs');
const data=await readFile('public/models/telescope/telescope.glb');
const gltf=await new GLTFLoader().parseAsync(data.buffer.slice(data.byteOffset,data.byteOffset+data.byteLength),'');
const load=GLTFLoader.prototype.loadAsync;
GLTFLoader.prototype.loadAsync=async()=>gltf;
const root=new THREE.Group(),targets=[];
const colliders=JSON.parse(await readFile('public/models/timi-studio/sunset-colliders.json','utf8'));
await loadTelescope(root,colliders,targets,()=>false);
GLTFLoader.prototype.loadAsync=load;
const scope=root.getObjectByName('asset-telescope');
const box=new THREE.Box3().setFromObject(scope);
assert(Math.abs(box.min.y-.02)<.001);
assert(Math.abs(box.max.y-1.62)<.001);
const collider=colliders.at(-1); console.log(collider,box.min.toArray(),box.max.toArray());
assert(collider.minX>-.05 && collider.maxX<1.101,'Telescope must fit between desk and bed');
assert(collider.minZ>-3.27,'Telescope must not cross window');
const origin=new THREE.Vector3(.525,1.62,-1.25);
const hits=new THREE.Raycaster(origin,new THREE.Vector3(.525,1.45,-2.43).sub(origin).normalize(),0,3.3).intersectObjects(targets,false);
assert(hits.length>0,'Reachable eye-level ray must hit telescope');
assert.equal(hits[0].object.userData.desktopMode,'orbit');
const desk=new THREE.Group();desk.userData={editable:true,assetId:'desk',label:'Desk'};desk.position.set(-1,0,-2.5);root.add(desk);
const layout=new SceneLayout(root,colliders);
const saved=layout.snapshot();saved.assets=saved.assets.filter(a=>a.id!=='telescope');saved.assets[0].position[0]=-.9;
layout.apply(saved);
assert.equal(layout.assets.find(a=>a.id==='desk').object.position.x,-.9);
assert.equal(layout.assets.find(a=>a.id==='telescope').object.position.x,.525);
console.log('PASS telescope fits desk/bed/window, eye-level E ray, previous-layout migration.',box.min.toArray(),box.max.toArray());
